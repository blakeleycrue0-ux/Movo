// Bundles the local auth shim + migrations into a TS module for the in-browser demo database.
// The storage/realtime migration is Supabase-only and is skipped.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migDir = join(root, "supabase", "migrations");
const files = readdirSync(migDir).filter((f) => f.endsWith(".sql") && !f.includes("storage_realtime")).sort();
const parts = [readFileSync(join(root, "supabase", "tests", "shim.sql"), "utf8"), ...files.map((f) => readFileSync(join(migDir, f), "utf8"))];
const sql = parts.join("\n;\n");
const version = createHash("sha256").update(sql).digest("hex").slice(0, 12);
const out = `// AUTO-GENERATED by scripts/gen-demo-sql.mjs — do not edit.\nexport const DEMO_SQL_VERSION = ${JSON.stringify(version)};\nexport const DEMO_SQL = ${JSON.stringify(sql)};\n`;
mkdirSync(join(root, "src", "lib", "demo"), { recursive: true });
writeFileSync(join(root, "src", "lib", "demo", "sql.generated.ts"), out);
console.log(`demo sql ${version} (${files.length} migrations)`);
